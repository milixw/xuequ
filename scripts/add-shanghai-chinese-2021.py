def apply(download):
    archive = download / RELATIVE
    if not archive.exists():
        print('未找到存档文件：%s' % archive)
        return 1
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    catalog = load()
    existing = {p['id']: p for p in catalog['papers']}
    if 'sh-chinese-2021' in existing:
        print('sh-chinese-2021 已存在，按要求不覆盖已有题目。')
        return 0
    paper = build(digest)
    catalog['papers'].append(paper)
    catalog['papers'].sort(key=lambda p: (p['subject'], -p['year']))
    save(catalog)
    print('已录入 sh-chinese-2021：%d 道整组题，来源 SHA-256 %s'
          % (len(paper['questions']), digest[:12]))
    print('交叉核对锚点：%s' % OFFICIAL_URL)
    print('缺图声明 %d 条。' % len(SKIPPED))
    return 0


