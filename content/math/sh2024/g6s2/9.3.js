const SOLVE93 = (a1, b1, c1, a2, b2, c2) => {
  [a1, b1, c1, a2, b2, c2] = [a1, b1, c1, a2, b2, c2].map(v => F(v));
  const d = a1.mul(b2).sub(a2.mul(b1));
  return [c1.mul(b2).sub(c2.mul(b1)).div(d), a1.mul(c2).sub(a2.mul(c1)).div(d)];
};

