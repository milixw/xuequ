const S215 = Math.sqrt;
const R215 = v => Math.round(v * 1e9) / 1e9;
const roots215 = (a, b, c) => {
  const d = b * b - 4 * a * c;
  if (d < -1e-12) return [];
  if (Math.abs(d) < 1e-12) return [-b / (2 * a)];
  return [(-b + S215(d)) / (2 * a), (-b - S215(d)) / (2 * a)];
};
