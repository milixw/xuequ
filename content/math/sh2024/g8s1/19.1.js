// 精确开 k 次方，开不尽返回 null。给 verify 独立算答案用（只在测试里跑）
const iroot = (x, k) => {
  const r = BigInt(Math.round(Math.pow(Number(x), 1 / k)));
  for (let t = r - 2n; t <= r + 2n; t++) if (t >= 0n && t ** BigInt(k) === x) return t;
  return null;
};
const nthRoot = (x, k) => {
  const f = F(x);
  const neg = f.n < 0n;
  if (neg && k % 2 === 0) return null;
  const n = iroot(neg ? -f.n : f.n, k);
  const d = iroot(f.d, k);
  if (n === null || d === null) return null;
  const r = F(`${n}/${d}`);
  return neg ? r.neg() : r;
};
